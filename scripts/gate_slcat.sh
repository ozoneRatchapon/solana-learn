#!/usr/bin/env bash
# gate ของการย้ายมา Rust: `slcat audit` ต้องเห็นข้อมูลตรงกับ `audit.sh`
#
#   ./scripts/gate_slcat.sh
#
# ทำไมต้องมี: การเขียนใหม่ที่ "น่าจะเหมือนเดิม" คือวิธีทำข้อมูลพังที่เนียนที่สุด
# ตราบใดที่ยังมีสองตัว ให้ทั้งคู่ตอบคำถามเดียวกันแล้วเทียบกัน — ตัวเก่าเป็น oracle
# เอาออกได้เมื่อย้ายครบและ gate ผ่านต่อเนื่อง ไม่ใช่เมื่อรู้สึกว่าพร้อม
#
# ส่วนที่ **ตั้งใจ** ให้ต่าง (ไม่นับว่าพัง):
#   - bash พิมพ์ "ทุก entry มี <ฟิลด์>" ทีละบรรทัด · rust ยุบเหลือบรรทัดเดียว
#     เพราะฟิลด์ที่ต้องมีถูกบังคับตั้งแต่ตอน parse — ไฟล์ที่ขาดฟิลด์โหลดไม่ขึ้นเลย
#   - bash มีชั้น 3 (คำอ้างในเอกสาร) กับ 4 (CATALOG ตรงกับ YAML) ที่ยังไม่ได้ย้าย
# gate นี้จึงเทียบเฉพาะ "ตัวเลขสรุป" ซึ่งเป็นข้อเท็จจริงที่ทั้งคู่ต้องเห็นเหมือนกัน

set -uo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

strip_ansi() { sed 's/\x1b\[[0-9;]*m//g'; }

# บรรทัดสรุป: "ผ่าน — N รายการ · M หมวด · ลิงก์ตาย D · note P% · ปฏิเสธไว้ R · เลิกใช้ X"
summary_of() { printf '%s' "$1" | strip_ansi | grep -E "^(ผ่าน|ไม่ผ่าน)" | sed 's/  (เตือน.*//'; }

bash_out="$(./scripts/audit.sh 2>&1)"
rust_out="$(cargo run -q -p slcat -- audit 2>&1)"

b="$(summary_of "$bash_out")"
r="$(summary_of "$rust_out")"

echo "  bash: $b"
echo "  rust: $r"
echo

if [ "$b" = "$r" ]; then
  echo "  ✅ ตัวเลขที่ทั้งสองฝั่งเห็นตรงกัน"
else
  echo "  ❌ ไม่ตรงกัน — อย่างใดอย่างหนึ่งอ่านข้อมูลผิด"
  exit 1
fi

# "หมวดที่ขาดหนักสุด" ต้องตรงด้วย เพราะมันคือการจัดอันดับ ไม่ใช่แค่ตัวนับ
# (เคยต่างกันมาแล้วตอน bash ใช้ `sort -rn` เฉยๆ ซึ่งไม่ stable — แก้ทั้งสองฝั่งแล้ว)
wb="$(printf '%s' "$bash_out" | strip_ansi | grep "หมวดที่ขาดหนักสุด" | tr -s ' ' | sed 's/ *$//')"
wr="$(printf '%s' "$rust_out" | strip_ansi | grep "หมวดที่ขาดหนักสุด" | tr -s ' ' | sed 's/ *$//')"
if [ "$wb" = "$wr" ]; then
  echo "  ✅ อันดับหมวดที่ขาด note ตรงกัน"
else
  echo "  ❌ อันดับต่างกัน:"
  echo "     bash: $wb"
  echo "     rust: $wr"
  exit 1
fi
